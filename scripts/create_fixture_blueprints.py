FIXTURES = {
    "strategy_heavy": strategy_heavy,
    "execution_heavy": execution_heavy,
    "data_heavy": data_heavy,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", required=True, help="Output directory for blueprint JSON files.")
    parser.add_argument("--style-pack", default="editorial_event_signal", help="Base style pack key.")
    parser.add_argument("--fixture", choices=sorted(FIXTURES), action="append", help="Fixture to create. Defaults to all.")
    args = parser.parse_args()

    style_pack = load_style_pack(args.style_pack)
    selected = args.fixture or sorted(FIXTURES)
    outdir = Path(args.outdir).resolve()
    outdir.mkdir(parents=True, exist_ok=True)

    for key in selected:
        data = FIXTURES[key](deepcopy(style_pack))
        path = outdir / f"{key}.json"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
