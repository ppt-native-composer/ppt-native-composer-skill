from copy import deepcopy
from pathlib import Path
from typing import Any


SKILL_DIR = Path(__file__).resolve().parents[1]
STYLE_LIBRARY = SKILL_DIR / "templates" / "style_packs" / "style_packs.json"


def load_style_pack(key: str) -> dict[str, Any]:
    payload = json.loads(STYLE_LIBRARY.read_text(encoding="utf-8"))
    packs = payload.get("style_packs", {})
    if key not in packs:
        raise SystemExit(f"Unknown style pack: {key}")
    return deepcopy(packs[key])


def visual_bible(style_pack: dict[str, Any]) -> dict[str, Any]:
    pal = style_pack.get("palette", {})
    return {
        "moodboard_reference": style_pack.get("reference_summary", ""),
        "style_direction": style_pack.get("quality_bar", ""),
        "design_tokens": {
            "colors": [
                pal.get("ink", "#111111"),
                pal.get("background", "#F7F3EC"),
                pal.get("accent", "#FF5A3D"),
                pal.get("secondary_accent", "#276EF1"),
                pal.get("muted", "#6E6A63"),
            ],
            "typography_tone": style_pack.get("typography", {}).get("title_character", ""),
            "shape_language": style_pack.get("composition_grammar", {}).get("grid", ""),
            "texture": style_pack.get("image_language", {}).get("texture", ""),
            "lighting": style_pack.get("image_language", {}).get("lighting", ""),
            "layout_density": style_pack.get("composition_grammar", {}).get("density_rule", ""),
        },
        "visual_motifs": style_pack.get("visual_motifs", []),
        "page_family_map": style_pack.get("page_families", {}),
        "asset_prompt_kit": {
            "shared_rendering_language": style_pack.get("asset_prompt_base", ""),
            "transparent_png_rules": "transparent background, no body copy, no logo, no QR code",
            "visual_text_rules": "only short concept phrases may become generated visual text",
            "negative_prompt": ", ".join(style_pack.get("do_not_use", [])),
        },
        "native_component_style": json.dumps(style_pack.get("native_component_skin", {}), ensure_ascii=False),
        "do_not_use": style_pack.get("do_not_use", []),
    }


def font_plan() -> dict[str, Any]:
    return {
        "cjk": "PingFang SC",
        "latin": "Aptos",
        "fallback": ["Microsoft YaHei", "Arial"],
        "hierarchy": {
            "title": "34-44pt editable title",
            "subtitle": "20-24pt editable argument",
            "body": "12-18pt editable body",
            "caption": "8-11pt utility captions",
            "data": "24-32pt editable key figures",
        },
        "display_text_policy": "Titles, body, numbers and execution details stay editable. Only short marked visual_text_assets may become raster assets.",
    }


def slide(
    n: int,
    title: str,
    purpose: str,
    content_type: str,
    mode: str,
    core: str,
    body: list[tuple[str, str]],
    *,
    component: str,
    role: str,
    structure: str,
    assets: list[dict[str, Any]] | None = None,
    visual_text: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    return {
        "slide_number": n,
        "title": title,
        "page_purpose": purpose,
        "content_type": content_type,
        "page_mode": mode,
        "core_message": core,
        "editable_text": [
            {"id": "title", "text": title, "role": "page title"},
            *[
                {"id": f"item_{idx}", "text": text, "role": role_text}
                for idx, (role_text, text) in enumerate(body, start=1)
            ],
        ],
        "visual_text_assets": visual_text or [],
        "image_assets": assets or [],
        "locked_raster": [],
        "visual_design_role": role,
        "visual_anchors": ["layout recipe", "component skin", "asset slot"],
        "native_structure": structure,
        "component_preset": component,
        "layout_notes": "Fixture slide used to test reusable native PPT component behavior.",
        "speaker_notes": f"Fixture note for {title}.",
    }


def deck(name: str, deck_type: str, objective: str, slides: list[dict[str, Any]], style_pack: dict[str, Any]) -> dict[str, Any]:
    return {
        "deck_brief": {
            "project_name": name,
            "deck_type": deck_type,
            "audience": "brand and event decision makers",
            "objective": objective,
            "creative_summary": "Fixture blueprint for PPT Native Composer generalization testing.",
            "production_notes": "Generated by create_fixture_blueprints.py.",
        },
        "visual_bible": visual_bible(style_pack),
        "style_pack": style_pack,
        "font_plan": font_plan(),
        "slides": slides,
    }


